/**
 * Оценка настроения — целое от 1 до 5. В дневнике пользователя нашлась
 * запись, где оценки нет или она не число, и график «Настроение по времени»
 * уронил приложение: react-native-svg на Android падает на NaN в координатах,
 * а в браузере то же самое молча рисуется. Всё, что считает или рисует по
 * настроению, пропускает такие записи через эту проверку.
 */
export function isValidMood(mood: unknown): mood is number {
  return typeof mood === "number" && Number.isInteger(mood) && mood >= 1 && mood <= 5;
}
